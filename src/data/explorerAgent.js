export function getExplorerDetailItem(lang = 'en') {
  const locale = ['zh', 'ko', 'en'].includes(lang) ? lang : 'en';
  const localized = getAgentLocale(explorer, locale);
  return {
    id: 'nexaeon-explorer',
    category: localized.moduleLabel,
    status: 'MVP Active',
    moduleLabel: 'NexAeon Agent System',
    title: explorer.name,
  };
}
