export function getXchangeDetailItem(lang = 'en') {
  const locale = ['zh', 'ko', 'en'].includes(lang) ? lang : 'en';
  const localized = getAgentLocale(xchange, locale);
  return {
    id: 'nexaeon-xchange',
    category: localized.moduleLabel,
    status: 'MVP Active',
    moduleLabel: 'NexAeon Agent System',
    title: xchange.name,
  };
}
