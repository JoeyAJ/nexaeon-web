export function getModuleData(moduleKey) {
  return MODULE_DATA
    .filter((item) => item.moduleKey === moduleKey)
    .sort((a, b) => (a.order || 999) - (b.order || 999));
}

export function getModuleStatus() {
  return MODULE_DATA_SOURCE_STATUS;
}

export function getModuleEndpoint(moduleKey) {
  return MODULE_ENDPOINTS[moduleKey];
}

export function getModuleFilters(moduleKey) {
  return MODULE_FILTERS[moduleKey] || MODULE_FILTERS.research;
}

export function getModulePageUi(moduleKey, lang = 'zh') {
  const ui = MODULE_PAGE_UI[moduleKey] || MODULE_PAGE_UI.research;
  const suffix = lang === 'ko' ? 'Ko' : lang === 'en' ? 'En' : 'Zh';

  return {
    title: ui[`title${suffix}`],
    subtitle: ui[`subtitle${suffix}`],
  };
}

export function getLocalizedModuleField(item, field, lang = 'zh') {
  const suffix = lang === 'ko' ? 'Ko' : lang === 'en' ? 'En' : 'Zh';
  return item[`${field}${suffix}`];
}

export function getLocalizedModuleStatus(lang = 'zh') {
  const suffix = lang === 'ko' ? 'Ko' : lang === 'en' ? 'En' : 'Zh';

  return {
    source: MODULE_DATA_SOURCE_STATUS[`source${suffix}`],
    connection: MODULE_DATA_SOURCE_STATUS[`connection${suffix}`],
  };
}

export function getModuleFilterLabel(filter, lang = 'zh') {
  if (lang === 'ko') return filter.ko;
  if (lang === 'en') return filter.en;
  return filter.zh;
}
